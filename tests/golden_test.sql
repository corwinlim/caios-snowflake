USE ROLE ACCOUNTADMIN;
USE DATABASE CAIOS;
-- USE WAREHOUSE <YOUR_WAREHOUSE>;

-- 1) Pet 360 gate
SELECT PET_KEY, PET_NAME, SPECIES, BREED, LIFE_STAGE, WEIGHT_KG,
       ACTIVITY_LEVEL, SOFT_STOOL_OBSERVATIONS, RECENT_GI_SIGNAL
FROM CAIOS.SEMANTIC.PET_360
WHERE PET_KEY = 'MILO-DEMO-001';
-- Expected: MILO-DEMO-001 / Milo / DOG / Golden Retriever / ADULT / 31.80 / MODERATE / 2 / TRUE

-- 2) Food comparison gate
SELECT CURRENT_FOOD_NAME, CANDIDATE_FOOD_NAME, ENERGY_DELTA_PCT, PROTEIN_SOURCE_CHANGED
FROM CAIOS.SEMANTIC.FOOD_COMPARISON;
-- Expected: Adult Chicken Formula / Sensitive Salmon Formula / 13.70 / TRUE

-- 3) Transition risk gate
