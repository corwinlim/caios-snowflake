CREATE DATABASE IF NOT EXISTS CAIOS;

CREATE SCHEMA IF NOT EXISTS CAIOS.CORE;
CREATE SCHEMA IF NOT EXISTS CAIOS.KNOWLEDGE;
CREATE SCHEMA IF NOT EXISTS CAIOS.EVIDENCE;
CREATE SCHEMA IF NOT EXISTS CAIOS.INTELLIGENCE;
CREATE SCHEMA IF NOT EXISTS CAIOS.SEMANTIC;
CREATE SCHEMA IF NOT EXISTS CAIOS.APP;

-- ---------------------------------------------------------
-- PET 360 FOUNDATION (CORE)
-- ---------------------------------------------------------

CREATE TABLE IF NOT EXISTS CAIOS.CORE.PET (
    PET_ID VARCHAR DEFAULT UUID_STRING(),
    PET_KEY VARCHAR NOT NULL,
    PET_NAME VARCHAR NOT NULL,
    SPECIES VARCHAR NOT NULL,
    DATE_OF_BIRTH DATE,
    SEX VARCHAR,
    NEUTER_STATUS VARCHAR,
    RECORD_SOURCE VARCHAR,
    CREATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    UPDATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS CAIOS.CORE.PET_PROFILE (
    PROFILE_ID VARCHAR DEFAULT UUID_STRING(),
    PET_ID VARCHAR NOT NULL,
    BREED VARCHAR,
    LIFE_STAGE VARCHAR,
    WEIGHT_KG NUMBER(10,2),
    ACTIVITY_LEVEL VARCHAR,
    EFFECTIVE_FROM TIMESTAMP_NTZ NOT NULL,
    EFFECTIVE_TO TIMESTAMP_NTZ,
    RECORD_SOURCE VARCHAR,
    CREATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS CAIOS.CORE.PET_OBSERVATION (
    OBSERVATION_ID VARCHAR DEFAULT UUID_STRING(),
    PET_ID VARCHAR NOT NULL,
    OBSERVATION_TYPE VARCHAR NOT NULL,
    OBSERVATION_VALUE VARCHAR,
    NUMERIC_VALUE NUMBER(18,4),
    UNIT VARCHAR,
    OBSERVED_AT TIMESTAMP_NTZ NOT NULL,
    SOURCE_TYPE VARCHAR,
    SOURCE_ID VARCHAR,
    RECORD_SOURCE VARCHAR,
    CREATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

-- ---------------------------------------------------------
-- FOOD KNOWLEDGE (KNOWLEDGE)
-- ---------------------------------------------------------

CREATE TABLE IF NOT EXISTS CAIOS.KNOWLEDGE.FOOD_PRODUCT (
    FOOD_PRODUCT_ID VARCHAR DEFAULT UUID_STRING(),
    FOOD_KEY VARCHAR NOT NULL,
    BRAND_NAME VARCHAR,
    PRODUCT_NAME VARCHAR NOT NULL,
    SPECIES VARCHAR,
    LIFE_STAGE VARCHAR,
    FOOD_FORM VARCHAR,
    PRIMARY_PROTEIN VARCHAR,
    ENERGY_KCAL_PER_100G NUMBER(10,2),
    RECORD_SOURCE VARCHAR,
    CREATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

-- ---------------------------------------------------------
-- MILO GOLDEN RECORD
-- ---------------------------------------------------------

MERGE INTO CAIOS.CORE.PET T USING (
    SELECT
        'MILO-DEMO-001' AS PET_KEY,
        'Milo' AS PET_NAME,
        'DOG' AS SPECIES,
        '2021-06-15'::DATE AS DATE_OF_BIRTH,
        'MALE' AS SEX,
        'NEUTERED' AS NEUTER_STATUS
) S ON T.PET_KEY = S.PET_KEY
WHEN MATCHED THEN UPDATE SET
    PET_NAME = S.PET_NAME,
    UPDATED_AT = CURRENT_TIMESTAMP()
WHEN NOT MATCHED THEN INSERT (
    PET_KEY, PET_NAME, SPECIES, DATE_OF_BIRTH, SEX, NEUTER_STATUS, RECORD_SOURCE
) VALUES (
    S.PET_KEY, S.PET_NAME, S.SPECIES, S.DATE_OF_BIRTH, S.SEX, S.NEUTER_STATUS, 'CAIOS_DEMO'
);

SET MILO_ID = (SELECT PET_ID FROM CAIOS.CORE.PET WHERE PET_KEY = 'MILO-DEMO-001');

INSERT INTO CAIOS.CORE.PET_PROFILE (
    PET_ID, BREED, LIFE_STAGE, WEIGHT_KG, ACTIVITY_LEVEL, EFFECTIVE_FROM, RECORD_SOURCE
)
SELECT $MILO_ID, 'Golden Retriever', 'ADULT', 31.8, 'MODERATE',
       '2026-09-01'::TIMESTAMP_NTZ, 'CAIOS_DEMO'
WHERE NOT EXISTS (
    SELECT 1 FROM CAIOS.CORE.PET_PROFILE
    WHERE PET_ID = $MILO_ID AND EFFECTIVE_TO IS NULL
);

-- ---------------------------------------------------------
-- SYNTHETIC FOODS
-- ---------------------------------------------------------

MERGE INTO CAIOS.KNOWLEDGE.FOOD_PRODUCT T USING (
    SELECT * FROM VALUES
        ('FOOD-CHICKEN-001', 'CAIOS Demo Nutrition', 'Adult Chicken Formula', 'DOG', 'ADULT', 'DRY', 'Chicken', 365.0),
        ('FOOD-SALMON-001',  'CAIOS Demo Nutrition', 'Sensitive Salmon Formula', 'DOG', 'ADULT', 'DRY', 'Salmon',  415.0)
    V(FOOD_KEY, BRAND_NAME, PRODUCT_NAME, SPECIES, LIFE_STAGE, FOOD_FORM, PRIMARY_PROTEIN, ENERGY_KCAL_PER_100G)
) S ON T.FOOD_KEY = S.FOOD_KEY
WHEN MATCHED THEN UPDATE SET
    PRODUCT_NAME = S.PRODUCT_NAME,
    PRIMARY_PROTEIN = S.PRIMARY_PROTEIN,
    ENERGY_KCAL_PER_100G = S.ENERGY_KCAL_PER_100G
WHEN NOT MATCHED THEN INSERT (
    FOOD_KEY, BRAND_NAME, PRODUCT_NAME, SPECIES, LIFE_STAGE, FOOD_FORM,
    PRIMARY_PROTEIN, ENERGY_KCAL_PER_100G, RECORD_SOURCE
) VALUES (
    S.FOOD_KEY, S.BRAND_NAME, S.PRODUCT_NAME, S.SPECIES, S.LIFE_STAGE, S.FOOD_FORM,
    S.PRIMARY_PROTEIN, S.ENERGY_KCAL_PER_100G, 'CAIOS_DEMO'
);

-- ---------------------------------------------------------
-- VERIFY
-- ---------------------------------------------------------

SELECT P.PET_KEY, P.PET_NAME, P.SPECIES, PR.BREED, PR.LIFE_STAGE, PR.WEIGHT_KG, PR.ACTIVITY_LEVEL
FROM CAIOS.CORE.PET P
JOIN CAIOS.CORE.PET_PROFILE PR ON P.PET_ID = PR.PET_ID
WHERE P.PET_KEY = 'MILO-DEMO-001';

SELECT FOOD_KEY, PRODUCT_NAME, PRIMARY_PROTEIN, ENERGY_KCAL_PER_100G
FROM CAIOS.KNOWLEDGE.FOOD_PRODUCT
ORDER BY FOOD_KEY;
