-- ---------------------------------------------------------
-- 2. PET 360 (semantic view)
-- ---------------------------------------------------------

CREATE OR REPLACE VIEW CAIOS.SEMANTIC.PET_360 AS
WITH CURRENT_PROFILE AS (
    SELECT *
    FROM CAIOS.CORE.PET_PROFILE
    QUALIFY ROW_NUMBER() OVER (
        PARTITION BY PET_ID ORDER BY EFFECTIVE_FROM DESC, CREATED_AT DESC
    ) = 1
),
LATEST_WEIGHT AS (
    SELECT PET_ID, NUMERIC_VALUE AS LATEST_WEIGHT_KG, OBSERVED_AT AS WEIGHT_OBSERVED_AT
    FROM CAIOS.CORE.PET_OBSERVATION
    WHERE OBSERVATION_TYPE = 'WEIGHT'
    QUALIFY ROW_NUMBER() OVER (
        PARTITION BY PET_ID ORDER BY OBSERVED_AT DESC, CREATED_AT DESC
    ) = 1
),
GI_CONTEXT AS (
    SELECT PET_ID,
        COUNT_IF(OBSERVATION_TYPE = 'STOOL_CONSISTENCY' AND OBSERVATION_VALUE = 'SOFT')
            AS SOFT_STOOL_OBSERVATIONS
    FROM CAIOS.CORE.PET_OBSERVATION
    GROUP BY PET_ID
)
SELECT
    P.PET_ID, P.PET_KEY, P.PET_NAME, P.SPECIES, P.DATE_OF_BIRTH,
    PR.BREED, PR.LIFE_STAGE,
    COALESCE(LW.LATEST_WEIGHT_KG, PR.WEIGHT_KG) AS WEIGHT_KG,
    PR.ACTIVITY_LEVEL,
    COALESCE(GI.SOFT_STOOL_OBSERVATIONS, 0) AS SOFT_STOOL_OBSERVATIONS,
    IFF(COALESCE(GI.SOFT_STOOL_OBSERVATIONS, 0) >= 2, TRUE, FALSE) AS RECENT_GI_SIGNAL
FROM CAIOS.CORE.PET P
LEFT JOIN CURRENT_PROFILE PR ON P.PET_ID = PR.PET_ID
LEFT JOIN LATEST_WEIGHT LW ON P.PET_ID = LW.PET_ID
LEFT JOIN GI_CONTEXT GI ON P.PET_ID = GI.PET_ID;

-- ---------------------------------------------------------
-- 3. Deterministic food comparison
-- ---------------------------------------------------------

CREATE OR REPLACE VIEW CAIOS.SEMANTIC.FOOD_COMPARISON AS
SELECT
    C.FOOD_KEY AS CURRENT_FOOD_KEY,
    C.PRODUCT_NAME AS CURRENT_FOOD_NAME,
    C.PRIMARY_PROTEIN AS CURRENT_PRIMARY_PROTEIN,
    C.ENERGY_KCAL_PER_100G AS CURRENT_ENERGY_KCAL_PER_100G,
    N.FOOD_KEY AS CANDIDATE_FOOD_KEY,
    N.PRODUCT_NAME AS CANDIDATE_FOOD_NAME,
    N.PRIMARY_PROTEIN AS CANDIDATE_PRIMARY_PROTEIN,
    N.ENERGY_KCAL_PER_100G AS CANDIDATE_ENERGY_KCAL_PER_100G,
    ROUND((N.ENERGY_KCAL_PER_100G - C.ENERGY_KCAL_PER_100G)
          / C.ENERGY_KCAL_PER_100G * 100, 2) AS ENERGY_DELTA_PCT,
    C.PRIMARY_PROTEIN <> N.PRIMARY_PROTEIN AS PROTEIN_SOURCE_CHANGED
FROM CAIOS.KNOWLEDGE.FOOD_PRODUCT C
CROSS JOIN CAIOS.KNOWLEDGE.FOOD_PRODUCT N
WHERE C.FOOD_KEY = 'FOOD-CHICKEN-001'
  AND N.FOOD_KEY = 'FOOD-SALMON-001';

-- ---------------------------------------------------------
-- 4. Deterministic transition risk
-- ---------------------------------------------------------

CREATE OR REPLACE VIEW CAIOS.INTELLIGENCE.MILO_TRANSITION_RISK AS
SELECT
    P.PET_KEY, P.PET_NAME,
    F.CURRENT_FOOD_NAME, F.CANDIDATE_FOOD_NAME,
    F.ENERGY_DELTA_PCT, F.PROTEIN_SOURCE_CHANGED,
    P.RECENT_GI_SIGNAL,
    IFF(F.PROTEIN_SOURCE_CHANGED, 1, 0) AS PROTEIN_CHANGE_SCORE,
    IFF(ABS(F.ENERGY_DELTA_PCT) > 10, 1, 0) AS ENERGY_CHANGE_SCORE,
    IFF(P.RECENT_GI_SIGNAL, 2, 0) AS GI_SIGNAL_SCORE,
    IFF(F.PROTEIN_SOURCE_CHANGED, 1, 0)
      + IFF(ABS(F.ENERGY_DELTA_PCT) > 10, 1, 0)
      + IFF(P.RECENT_GI_SIGNAL, 2, 0) AS RISK_SCORE,
    CASE
        WHEN IFF(F.PROTEIN_SOURCE_CHANGED, 1, 0)
             + IFF(ABS(F.ENERGY_DELTA_PCT) > 10, 1, 0)
             + IFF(P.RECENT_GI_SIGNAL, 2, 0) >= 4 THEN 'HIGH'
        WHEN IFF(F.PROTEIN_SOURCE_CHANGED, 1, 0)
             + IFF(ABS(F.ENERGY_DELTA_PCT) > 10, 1, 0)
             + IFF(P.RECENT_GI_SIGNAL, 2, 0) >= 2 THEN 'MODERATE'
        ELSE 'LOW'
    END AS RISK_LEVEL,
    'TRANSITION_RISK_V1' AS RISK_RULE_VERSION
FROM CAIOS.SEMANTIC.PET_360 P
CROSS JOIN CAIOS.SEMANTIC.FOOD_COMPARISON F
WHERE P.PET_KEY = 'MILO-DEMO-001';

